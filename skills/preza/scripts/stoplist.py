"""Стоп-список сдачи: фразы о происхождении содержимого и служебные пометки (общий для check_deck и check_speech).

Страховка, а не детектор: подписи о происхождении картинок агент не пишет вовсе (deck-house-rules), а здесь —
только точные формы («сгенерировано нейросетью», «Иллюстрация: Midjourney», «generated by AI»). Предпочитаем
пропуск ложной находке: ИИ как тема («Создание ИИ требует данных», «Источник: AI Index 2024») проходит.
Редкие совпадения в колоде про ИИ снимает --allow по контексту находки. STRICT — личные правила владельца (симуляция, номера ДЗ, даты актуальности): только --strict.
"""

import re

# ИИ/AI — не часть слова и не название подразделения («ИИ-отдел», «AI Lab»); названия генераторов — с окончаниями
AI = r"(?:ИИ|AI)(?![\w‑-])(?!\s+(?:отдел|лаборатор|lab|департамент|центр|команд|подразделени|направлени)\w*)"
TOOL = (
    r"(?:"
    + AI
    + r"|искусственн\w+\s+интеллект\w*|нейросет\w*|Midjourney\w*|DALL[\s·\-‑–]?E(?:\s*\d)?"
    r"|Kandinsky\w*|Кандинск\w+|Шедеврум\w*|Stable\s+Diffusion|ChatGPT\w*|GigaChat\w*|YandexART\w*)"
)
STOP = re.compile(
    # «создано с помощью ИИ», «Иллюстрация выполнена нейросетью», «сгенерировано в Шедевруме»
    # только причастие («создано», не «создание»); без предлога — творительный падеж («нейросетью», не «нейросеть»)
    r"(?:сгенерирован|создан|сделан|нарисован|выполнен)(?:о|а|ы|н[оаы]е?|ное|ная|ный|ные)?(?![\w])\s+(?:"
    r"(?:с помощью|при помощи|в|через)\s+" + TOOL + r"|" + AI + r"|искусственн\w+м\s+интеллект\w*|нейросеть\w+"
    r"|Midjourney|DALL[\s·\-‑–]?E|Kandinsky|Кандинским|Шедеврумом|ChatGPT|GigaChat|YandexART)"
    # подписи: «Иллюстрация: Midjourney», «Источник изображения: Kandinsky 3.1», «Иллюстрация: авторская»
    # после имени в подписи — только конец строки, номер версии или точка («Источник: AI Index 2024» проходит)
    + r"|(?:иллюстрац|изображени|рисун|картинк|фото|источник)\w*(?:\s+изображени\w*)?\s*[:—–-]\s*(?:(?:"
    + TOOL
    + r")(?:\s*v?\d[\d.]*)?(?=\s*(?:[.;,)]|$))|авторск\w*)"
    # «ИИ-иллюстрация», «AI-generated», «generated by AI»
    + r"|(?<![\w])(?:ИИ|AI)[-‑]иллюстрац\w*"
    + r"|(?<![\w])AI[\s\-‑–]generated|(?:generated|created|made)\s+(?:by|with)\s+"
    + TOOL
    # служебные следы инструментов
    + r"|imagegen|gpt-image|авторская иллюстрация",
    re.I | re.M,  # $ — конец строки подписи внутри многострочного текста
)
STRICT = re.compile(
    r"симуляц\w*|смоделирован\w*|синтетическ\w*"
    r"|\bДЗ\s*-?\s*\d|домашн\w+ задани\w+\s*№?\s*\d"
    r"|данные (?:на|по состоянию на)\s+\d|построен\w* автором",
    re.I,
)


def findings(text, strict=False, allow=None):
    """[(фрагмент, строгое ли правило)]; allow — регулярка по контексту ±20 знаков вокруг находки."""
    out = []
    for pattern, is_strict in ((STOP, False), (STRICT, True)):
        if is_strict and not strict:
            continue
        for m in pattern.finditer(text):
            context = text[max(0, m.start() - 20) : m.end() + 20]
            if allow and re.search(allow, context, re.I):
                continue
            out.append((m.group(0), is_strict))
    return out


def selftest():
    clean = (
        "информации о компании",
        "РОССИИ",
        "модели ИИ меняют рынок",
        "сгенерированный денежный поток",
        "Нейросеть меняет отрасль",
        "Рынок ИИ-генерации растёт",
        "Kandinsky от Сбера и Шедеврум",
        "Midjourney, DALL-E, Stable Diffusion",
        "выполнен в AI-лаборатории",
        "Bonsai изображение",
        "создано в ИИ-лаборатории",
        "Рынок ИИ изображений растёт",
        "Нейросетевые изображения: правовой статус",
        "ИИ-картинки в рекламе",
        "продукт создан в ИИ отделе",
        "модель создана в AI Lab",
        "Фото: РИА Новости",
        "Создание ИИ требует данных",
        "Роль государства в создании ИИ",
        "Выполнение нейросетью задач",
        "Создана нейросеть для диагностики",
        "создан искусственный интеллект нового поколения",
        "выполнены нейросетевые расчёты",
        "Источник: AI Index 2024",
        "Источник: ChatGPT Enterprise usage report",
        "Источник: нейросетевые модели в экономике (Иванов, 2023)",
        "Иллюстрация: ИИ в медицине",
        "Картинка — нейросеть распознаёт котов",
    )
    for text in clean:
        assert findings(text, strict=True) == [], (text, findings(text, strict=True))
    bad = (
        "сгенерировано нейросетью",
        "Изображение создано с помощью ИИ",
        "Иллюстрация: авторская",
        "нарисовано в DALL‑E",
        "сделано в Midjourney",
        "AI-generated",
        "ИИ-иллюстрация",
        "imagegen",
        "Иллюстрация: Midjourney",
        "Изображение: DALL·E 3",
        "Источник изображения: Kandinsky 3.1",
        "Generated with DALL-E",
        "Иллюстрация выполнена нейросетью",
        "Сгенерировано в Шедевруме",
        "создано искусственным интеллектом",
        "сгенерирован ChatGPT",
        "generated by AI",
        "создано ИИ",
    )
    for text in bad:
        assert findings(text), text
    for personal in ("смоделировано", "ДЗ2", "Данные на 01.10", "в домашнем задании 2"):
        assert findings(personal) == [] and findings(personal, strict=True), personal
    assert (
        findings("Обложка сделана в Midjourney для примера", allow="для примера") == []
    )
    assert findings("Тема слайда\nИллюстрация: Midjourney\nДалее текст"), "подпись в середине текста"
    print("selftest ok")


if __name__ == "__main__":
    selftest()
